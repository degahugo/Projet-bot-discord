package org.acme.bot.processors.resource;

import com.google.auto.service.AutoService;
import org.acme.bot.processors.annotations.GenerateEntity;
import org.acme.bot.processors.annotations.GenerateResource;
import org.acme.bot.processors.annotations.GenerateService;
import org.acme.bot.processors.annotations.Unique;

import javax.annotation.processing.AbstractProcessor;
import javax.annotation.processing.Messager;
import javax.annotation.processing.ProcessingEnvironment;
import javax.annotation.processing.Processor;
import javax.annotation.processing.RoundEnvironment;
import javax.annotation.processing.SupportedAnnotationTypes;
import javax.lang.model.SourceVersion;
import javax.lang.model.element.Element;
import javax.lang.model.element.ElementKind;
import javax.lang.model.element.RecordComponentElement;
import javax.lang.model.element.TypeElement;
import javax.tools.Diagnostic;
import java.io.IOException;
import java.io.Writer;
import java.util.List;
import java.util.Set;

/**
 *
 * For each record with annotation @GenerateResource : generate an ...Resource class (REST API)
 * which uses the ...Service generated by the ProcessorService
 * and the ...DTO / ...CreateRequest generated by the ProcessorDTO.
 *
 */
@SupportedAnnotationTypes("org.acme.bot.processors.annotations.GenerateResource")
@AutoService(Processor.class)
public class ProcessorResource extends AbstractProcessor {

    private static final String RESOURCE_PACKAGE="org.acme.bot.api.resource";

    /**
     *The string format for the Resource class
     * (a lot of values : we use named markers {{...}} instead of %s, easier to read)
     */
    private static final String RESOURCE_CLASS_PATTERN= """
                    package org.acme.bot.api.resource;

                    import jakarta.inject.Inject;
                    import jakarta.validation.Valid;
                    import jakarta.ws.rs.Consumes;
                    import jakarta.ws.rs.DELETE;
                    import jakarta.ws.rs.GET;
                    import jakarta.ws.rs.POST;
                    import jakarta.ws.rs.Path;
                    import jakarta.ws.rs.PathParam;
                    import jakarta.ws.rs.Produces;
                    import jakarta.ws.rs.core.MediaType;
                    import jakarta.ws.rs.core.Response;
                    import org.acme.bot.application.dto.{{Model}}CreateRequest;
                    import org.acme.bot.application.dto.{{Model}}DTO;
                    import org.acme.bot.application.services.{{Model}}Service;
                    import org.eclipse.microprofile.openapi.annotations.Operation;
                    import org.eclipse.microprofile.openapi.annotations.enums.SchemaType;
                    import org.eclipse.microprofile.openapi.annotations.media.Content;
                    import org.eclipse.microprofile.openapi.annotations.media.Schema;
                    import org.eclipse.microprofile.openapi.annotations.responses.APIResponse;
                    import org.eclipse.microprofile.openapi.annotations.tags.Tag;

                    import java.util.List;

                    /**
                     *
                     * REST resource of the {{Model}} Model : API with validation and documentation.
                     * (generated by the ProcessorResource)
                     *
                     */
                    @Path("/api/v1/{{table}}")
                    @Produces(MediaType.APPLICATION_JSON)
                    @Consumes(MediaType.APPLICATION_JSON)
                    @Tag(name="{{Model}}", description="Validated and documented API for {{Model}}")
                    public class {{Model}}Resource {

                        private final {{Model}}Service service;

                        @Inject
                        public {{Model}}Resource({{Model}}Service service) {
                            this.service = service;
                        }

                        /**
                         *
                         * @return a list of all {{Model}} mapped to DTOs.
                         *
                         */
                        @GET
                        @Operation(summary="Get all {{Model}}", description="Returns a list of all {{Model}}")
                        @APIResponse(responseCode="200",description="List of {{Model}}",content=@Content(mediaType="application/json",schema=@Schema(implementation={{Model}}DTO.class,type=SchemaType.ARRAY)))
                        public List<{{Model}}DTO> getAll(){
                            return service.getAll();
                        }

                        /**
                         *
                         * @return the {{Model}} with this {{key}}, or 404 if it does not exist
                         *
                         */
                        @GET
                        @Path("/{{{key}}}")
                        @Operation(summary="Get a {{Model}} by its {{key}}", description="Returns the {{Model}} with this {{key}}")
                        @APIResponse(responseCode="200",description="{{Model}} found",content=@Content(mediaType="application/json",schema=@Schema(implementation={{Model}}DTO.class)))
                        @APIResponse(responseCode="404",description="{{key}} not found")
                        public {{Model}}DTO getBy{{Key}}(@PathParam("{{key}}") {{KeyType}} {{key}}){
                            return service.getBy{{Key}}({{key}});
                        }

                        /**
                         *
                         * Create a new {{Model}}
                         *
                         */
                        @POST
                        @Operation(summary="Create a new {{Model}}",description="Validates input and persists a new {{Model}}")
                        @APIResponse(responseCode="201",description="{{Model}} succesfully created",content=@Content(mediaType="application/json",schema=@Schema(implementation={{Model}}DTO.class)))
                        @APIResponse(responseCode="400",description="Invalid input or domain validation failure")
                        @APIResponse(responseCode="409",description="{{key}} already exists")
                        public Response create(@Valid {{Model}}CreateRequest request){
                            {{Model}}DTO created=service.create(request);
                            return Response.status(Response.Status.CREATED).entity(created).build();
                        }

                        /**
                         *
                         *Delete a {{Model}}
                         */
                        @DELETE
                        @Path("/{{{key}}}")
                        @Operation(summary="Delete a {{Model}}",description="Deletes the {{Model}} with this {{key}}")
                        @APIResponse(responseCode="204",description="{{Model}} deleted")
                        @APIResponse(responseCode="404",description="{{key}} not found")
                        public Response delete(@PathParam("{{key}}") {{KeyType}} {{key}}){
                            service.delete({{key}});
                            return Response.noContent().build();
                        }
                    }
                    """;

    /**
     * A Messager to emit messages during annotation processing
     */
    private Messager messager;

    /**
     *
     * @return the latest supported version of Java
     */
    @Override
    public SourceVersion getSupportedSourceVersion() {
        return SourceVersion.latestSupported();
    }

    /**
     * Initializes the processor with the processing environment
     *
     * @param processingEnv environment to access facilities the tool framework
     */
    @Override
    public synchronized void init(ProcessingEnvironment processingEnv) {
        messager = processingEnv.getMessager();
        super.init(processingEnv);
    }


    @Override
    public boolean process(Set<? extends TypeElement> annotations, RoundEnvironment roundEnv) {

        for (Element element : roundEnv.getElementsAnnotatedWith(GenerateResource.class)) {

            // the annotation can only be used on a record
            if (element.getKind() != ElementKind.RECORD) {
                messager.printMessage(Diagnostic.Kind.ERROR, "@GenerateResource ne peut être placé que sur un record", element);
                continue;
            }

            // the resource uses the service : it must be generated too
            // (the ProcessorService already checks @GenerateEntity, @GenerateRepository, @GenerateMapper)
            if (element.getAnnotation(GenerateService.class) == null) {
                messager.printMessage(Diagnostic.Kind.ERROR, "@GenerateResource nécessite aussi @GenerateService sur le record", element);
                continue;
            }

            TypeElement model = (TypeElement) element;

            // get the model class name
            String modelName=model.getSimpleName().toString();
            String resourceName=modelName+"Resource";

            // the URL uses the name of the table : @GenerateEntity("roles") -> /api/v1/roles
            String tableName=model.getAnnotation(GenerateEntity.class).value();
            if (tableName.isBlank()) {
                tableName=modelName.toLowerCase();
            }

            // the business key : the only field with @Unique (Role -> name)
            List<? extends RecordComponentElement> keys = model.getRecordComponents().stream()
                    .filter(field -> field.getAnnotation(Unique.class) != null)
                    .toList();

            if (keys.size() != 1) {
                // the ProcessorService already shows the error
                continue;
            }

            RecordComponentElement key = keys.get(0);
            String keyType = key.asType().toString();
            String keyName = key.getSimpleName().toString();
            String KeyName = keyName.substring(0, 1).toUpperCase() + keyName.substring(1);

            //the class patern : we replace the markers
            // ({{{key}}} in @Path("/{{{key}}}") gives @Path("/{name}") : the { } of JAX-RS around {{key}})

            String resourceClass=RESOURCE_CLASS_PATTERN
                    .replace("{{Model}}", modelName)
                    .replace("{{table}}", tableName)
                    .replace("{{KeyType}}", keyType)
                    .replace("{{Key}}", KeyName)
                    .replace("{{key}}", keyName);

            // we write the .java file : javac will compile it

            try{
                var file=processingEnv.getFiler().createSourceFile(RESOURCE_PACKAGE+"."+resourceName,model);
                try(Writer writer=file.openWriter()){
                    writer.write(resourceClass);
                }
                messager.printMessage(Diagnostic.Kind.NOTE, "Resource generation for %s (%s)".formatted(modelName, resourceName));
            } catch (IOException e) {
                messager.printMessage(Diagnostic.Kind.ERROR, "Impossible de générer "+resourceName, model);
            }
        }
        return true;
    }
}