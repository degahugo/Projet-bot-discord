package org.acme.bot.processors.repository;

import com.google.auto.service.AutoService;
import org.acme.bot.processors.annotations.GenerateEntity;
import org.acme.bot.processors.annotations.GenerateRepository;
import org.acme.bot.processors.annotations.Unique;

import javax.annotation.processing.AbstractProcessor;
import javax.annotation.processing.Messager;
import javax.annotation.processing.ProcessingEnvironment;
import javax.annotation.processing.Processor;
import javax.annotation.processing.RoundEnvironment;
import javax.annotation.processing.SupportedAnnotationTypes;
import javax.lang.model.SourceVersion;
import javax.lang.model.element.Element;
import javax.lang.model.element.ElementKind;
import javax.lang.model.element.RecordComponentElement;
import javax.lang.model.element.TypeElement;
import javax.tools.Diagnostic;
import java.io.IOException;
import java.io.Writer;
import java.util.Set;

/**
 *
 * For each record with annotation @GenerateRepository(table="...") : generate an ...Repository class (Panache Repository)
 * for the XEntity generated by the ProcessorEntity.
 *
 */
@SupportedAnnotationTypes("org.acme.bot.processors.annotations.GenerateRepository")
@AutoService(Processor.class)
public class ProcessorRepository extends AbstractProcessor {

    private static final String ENTITY_PACKAGE="org.acme.bot.infrastructure.persistence.entity";
    private static final String REPOSITORY_PACKAGE ="org.acme.bot.infrastructure.persistence.repository";

    /**
     *The string format for the Entity class
     */
    private static final String REPOSITORY_CLASS_PATTERN= """
        package %s;

        import io.quarkus.hibernate.orm.panache.PanacheRepository;
        import jakarta.enterprise.context.ApplicationScoped;
        import %s.%s;

        import java.util.Optional;

        @ApplicationScoped
        public class %s implements PanacheRepository<%s> {

        %s
        }
        """;

    /**
     * A Messager to emit messages during annotation processing
     */
    private Messager messager;

    /**
     *
     * @return the latest supported version of Java
     */
    @Override
    public SourceVersion getSupportedSourceVersion() {
        return SourceVersion.latestSupported();
    }

    /**
     * Initializes the processor with the processing environment
     *
     * @param processingEnv environment to access facilities the tool framework
     */
    @Override
    public synchronized void init(ProcessingEnvironment processingEnv) {
        messager = processingEnv.getMessager();
        super.init(processingEnv);
    }


    @Override
    public boolean process(Set<? extends TypeElement> annotations, RoundEnvironment roundEnv) {
        //Set<? extends Element> elements = roundEnv.getElementsAnnotatedWith(GenerateRepository.class);

        for (Element element : roundEnv.getElementsAnnotatedWith(GenerateRepository.class)) {

            // the annotation can only be used on a record
            if (element.getKind() != ElementKind.RECORD) {
                messager.printMessage(Diagnostic.Kind.ERROR, "@GenerateRepository ne peut être placé que sur un record", element);
                continue;
            }

            // a repository needs an entity : the record must also have @GenerateEntity
            if (element.getAnnotation(GenerateEntity.class) == null) {
                messager.printMessage(Diagnostic.Kind.ERROR, "@GenerateRepository nécessite aussi @GenerateEntity sur le record", element);
                continue;
            }

            TypeElement model = (TypeElement) element;

            // get the model class name
            String modelName=model.getSimpleName().toString();
            String entityName=modelName+"Entity";
            String repositoryName=modelName+"Repository";

            // for each @Unique field : a findByXxx method
            String methods="";

            for (RecordComponentElement field : model.getRecordComponents()) {

                if (field.getAnnotation(Unique.class) == null) {
                    continue;
                }

                String fieldType = field.asType().toString();
                String fieldName = field.getSimpleName().toString();
                String Name = fieldName.substring(0, 1).toUpperCase() + fieldName.substring(1);

                methods+="    public Optional<"+entityName+"> findBy"+Name+"("+fieldType+" "+fieldName+"){\n";
                methods+="        return find(\""+fieldName+"\","+fieldName+").firstResultOptional();\n";
                methods+="    }\n";
            }

            //the class patern (once all the fields are read)

            String repositoryClass=REPOSITORY_CLASS_PATTERN.formatted(
                    REPOSITORY_PACKAGE,ENTITY_PACKAGE,entityName,repositoryName,entityName,methods);

            // we write the .java file : javac will compile it

            try{
                var file=processingEnv.getFiler().createSourceFile(REPOSITORY_PACKAGE+"."+repositoryName,model);
                try(Writer writer=file.openWriter()){
                    writer.write(repositoryClass);
                }
                messager.printMessage(Diagnostic.Kind.NOTE, "Repository generation for %s (%s)".formatted(modelName, repositoryName));
            } catch (IOException e) {
                messager.printMessage(Diagnostic.Kind.ERROR, "Impossible de générer "+repositoryName, model);
            }
        }
        return true;
    }
}
