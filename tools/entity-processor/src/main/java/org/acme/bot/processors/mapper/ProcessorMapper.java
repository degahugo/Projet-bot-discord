package org.acme.bot.processors.mapper;

import com.google.auto.service.AutoService;
import org.acme.bot.processors.annotations.DTO;
import org.acme.bot.processors.annotations.GenerateEntity;
import org.acme.bot.processors.annotations.GenerateMapper;

import javax.annotation.processing.AbstractProcessor;
import javax.annotation.processing.Messager;
import javax.annotation.processing.ProcessingEnvironment;
import javax.annotation.processing.Processor;
import javax.annotation.processing.RoundEnvironment;
import javax.annotation.processing.SupportedAnnotationTypes;
import javax.lang.model.SourceVersion;
import javax.lang.model.element.Element;
import javax.lang.model.element.ElementKind;
import javax.lang.model.element.RecordComponentElement;
import javax.lang.model.element.TypeElement;
import javax.tools.Diagnostic;
import java.io.IOException;
import java.io.Writer;
import java.util.Arrays;
import java.util.Set;

/**
 *
 * For each record with annotation @GenerateMapper : generate an ...Mapper class
 * which uses the classes generated by the other processors :
 * ...Entity (ProcessorEntity), ...DTO and ...CreateRequest (ProcessorDTO).
 *
 */
@SupportedAnnotationTypes("org.acme.bot.processors.annotations.GenerateMapper")
@AutoService(Processor.class)
public class ProcessorMapper extends AbstractProcessor {

    private static final String ENTITY_PACKAGE="org.acme.bot.infrastructure.persistence.entity";
    private static final String DTO_PACKAGE="org.acme.bot.application.dto";
    private static final String MAPPER_PACKAGE="org.acme.bot.infrastructure.mapper";

    /**
     *The string format for the Mapper class
     */
    private static final String MAPPER_CLASS_PATTERN= """
                    package %s;

                    import %s.%s;
                    import %s.%s;
                    import %s.%s;
                    import %s;

                    /**
                     *
                     *Component responsible for transforming data between architectural layers
                     *(generated by the ProcessorMapper)
                     *
                     */
                    public final class %s {

                        private %s(){
                            // Prevent instantiation of utility class
                        }

                        /**
                         *
                         * Maps a Persistence Entity to an API Response DTO
                         * the entity goes back through the Domain model (its rules are checked again)
                         *
                         */
                        public static %s toDto(%s entity){
                            return %s.from(entity.toModel());
                        }

                        /**
                         *
                         *Maps an API Request DTO to a Persistence Entity via the Domain model
                         *
                         */
                        public static %s toEntity(%s request){
                            // Step 1 : Create a Domain Object (Domain Rule Validation)
                            var domain = new %s(%s);

                            //Step 2 : Convert to Persistence Entity
                            return %s.fromModel(domain);
                        }
                    }
                    """;

    /**
     * A Messager to emit messages during annotation processing
     */
    private Messager messager;

    /**
     *
     * @return the latest supported version of Java
     */
    @Override
    public SourceVersion getSupportedSourceVersion() {
        return SourceVersion.latestSupported();
    }

    /**
     * Initializes the processor with the processing environment
     *
     * @param processingEnv environment to access facilities the tool framework
     */
    @Override
    public synchronized void init(ProcessingEnvironment processingEnv) {
        messager = processingEnv.getMessager();
        super.init(processingEnv);
    }


    @Override
    public boolean process(Set<? extends TypeElement> annotations, RoundEnvironment roundEnv) {

        for (Element element : roundEnv.getElementsAnnotatedWith(GenerateMapper.class)) {

            // the annotation can only be used on a record
            if (element.getKind() != ElementKind.RECORD) {
                messager.printMessage(Diagnostic.Kind.ERROR, "@GenerateMapper ne peut être placé que sur un record", element);
                continue;
            }

            // a mapper needs an entity : the record must also have @GenerateEntity
            if (element.getAnnotation(GenerateEntity.class) == null) {
                messager.printMessage(Diagnostic.Kind.ERROR, "@GenerateMapper nécessite aussi @GenerateEntity sur le record", element);
                continue;
            }

            TypeElement model = (TypeElement) element;

            // get the model class name
            String modelName=model.getSimpleName().toString();
            String modelClass=model.getQualifiedName().toString();
            String entityName=modelName+"Entity";                // generated by the ProcessorEntity
            String dtoName=modelName+"DTO";                      // generated by the ProcessorDTO (@DTO("DTO"))
            String createRequestName=modelName+"CreateRequest";  // generated by the ProcessorDTO (@DTO("CreateRequest"))
            String mapperName=modelName+"Mapper";

            // for each field : it must be in the DTO and in the CreateRequest
            // (to build the model from the request, the request needs ALL the fields of the model)
            String constructorArgs="";
            boolean valid=true;

            for (RecordComponentElement field : model.getRecordComponents()) {

                String fieldName = field.getSimpleName().toString();
                DTO[] dtos = field.getAnnotationsByType(DTO.class);

                boolean inDto = Arrays.stream(dtos).anyMatch(d -> d.value().equals("DTO"));
                boolean inCreateRequest = Arrays.stream(dtos).anyMatch(d -> d.value().equals("CreateRequest"));

                if (!inDto || !inCreateRequest) {
                    messager.printMessage(Diagnostic.Kind.ERROR,
                            "@GenerateMapper : le champ '"+fieldName+"' doit avoir @DTO(\"DTO\") et @DTO(\"CreateRequest\")", field);
                    valid=false;
                }

                constructorArgs+=(constructorArgs.isEmpty() ? "" : ", ")+"request."+fieldName+"()";
            }

            if (!valid) {
                continue;
            }

            //the class patern (once all the fields are read)

            String mapperClass=MAPPER_CLASS_PATTERN.formatted(
                    MAPPER_PACKAGE,
                    DTO_PACKAGE,dtoName,
                    DTO_PACKAGE,createRequestName,
                    ENTITY_PACKAGE,entityName,
                    modelClass,
                    mapperName,mapperName,
                    dtoName,entityName,dtoName,
                    entityName,createRequestName,modelName,constructorArgs,entityName);

            // we write the .java file : javac will compile it

            try{
                var file=processingEnv.getFiler().createSourceFile(MAPPER_PACKAGE+"."+mapperName,model);
                try(Writer writer=file.openWriter()){
                    writer.write(mapperClass);
                }
                messager.printMessage(Diagnostic.Kind.NOTE, "Mapper generation for %s (%s)".formatted(modelName, mapperName));
            } catch (IOException e) {
                messager.printMessage(Diagnostic.Kind.ERROR, "Impossible de générer "+mapperName, model);
            }
        }
        return true;
    }
}
