package org.acme.bot.processors.service;

import com.google.auto.service.AutoService;
import org.acme.bot.processors.annotations.GenerateEntity;
import org.acme.bot.processors.annotations.GenerateMapper;
import org.acme.bot.processors.annotations.GenerateRepository;
import org.acme.bot.processors.annotations.GenerateService;
import org.acme.bot.processors.annotations.Unique;

import javax.annotation.processing.AbstractProcessor;
import javax.annotation.processing.Messager;
import javax.annotation.processing.ProcessingEnvironment;
import javax.annotation.processing.Processor;
import javax.annotation.processing.RoundEnvironment;
import javax.annotation.processing.SupportedAnnotationTypes;
import javax.lang.model.SourceVersion;
import javax.lang.model.element.Element;
import javax.lang.model.element.ElementKind;
import javax.lang.model.element.RecordComponentElement;
import javax.lang.model.element.TypeElement;
import javax.tools.Diagnostic;
import java.io.IOException;
import java.io.Writer;
import java.util.List;
import java.util.Set;

/**
 *
 * For each record with annotation @GenerateService : generate an ...Service class (CRUD use cases)
 * which uses the classes generated by the other processors :
 * ...Repository (ProcessorRepository), ...Mapper (ProcessorMapper), ...DTO and ...CreateRequest (ProcessorDTO).
 *
 */
@SupportedAnnotationTypes("org.acme.bot.processors.annotations.GenerateService")
@AutoService(Processor.class)
public class ProcessorService extends AbstractProcessor {

    private static final String SERVICE_PACKAGE="org.acme.bot.application.services";

    /**
     *The string format for the Service class
     * (a lot of values : we use named markers {{...}} instead of %s, easier to read)
     */
    private static final String SERVICE_CLASS_PATTERN= """
                    package org.acme.bot.application.services;

                    import jakarta.enterprise.context.ApplicationScoped;
                    import jakarta.transaction.Transactional;
                    import org.acme.bot.application.dto.{{Model}}CreateRequest;
                    import org.acme.bot.application.dto.{{Model}}DTO;
                    import org.acme.bot.application.exceptions.ModelAlreadyExistsException;
                    import org.acme.bot.application.exceptions.ModelNotFoundException;
                    import org.acme.bot.infrastructure.mapper.{{Model}}Mapper;
                    import org.acme.bot.infrastructure.persistence.entity.{{Model}}Entity;
                    import org.acme.bot.infrastructure.persistence.repository.{{Model}}Repository;

                    import java.util.List;

                    /**
                     *
                     * Service of the {{Model}} Model
                     * (generated by the ProcessorService)
                     *
                     */
                    @ApplicationScoped
                    public class {{Model}}Service {

                        private final {{Model}}Repository repository;

                        public {{Model}}Service({{Model}}Repository repository){
                            this.repository = repository;
                        }

                        /**
                         *
                         * Retrieves all {{Model}}
                         *
                         */
                        public List<{{Model}}DTO> getAll(){
                            return repository.listAll().stream()
                                    .map({{Model}}Mapper::toDto).toList();
                        }

                        /**
                         *
                         * Retrieves a {{Model}} by its {{key}}
                         *
                         */
                        public {{Model}}DTO getBy{{Key}}({{KeyType}} {{key}}){
                            return repository.findBy{{Key}}({{key}})
                                    .map({{Model}}Mapper::toDto)
                                    .orElseThrow(()-> new ModelNotFoundException("{{Model}}", {{key}}));
                        }

                        /**
                         *
                         * Create a {{Model}} using business logic
                         *
                         */
                        @Transactional
                        public {{Model}}DTO create({{Model}}CreateRequest request){
                            //Step 1 : Mapping (Validation happens inside Mapper/Domain Record)
                            {{Model}}Entity entity={{Model}}Mapper.toEntity(request);

                            //Step 2 : Integrity Rule (the {{key}} is unique -> HTTP 409)
                            if(repository.findBy{{Key}}(entity.get{{Key}}()).isPresent()){
                                throw new ModelAlreadyExistsException("{{Model}}", entity.get{{Key}}());
                            }

                            //Step 3 :  Persistence via Panache
                            repository.persist(entity);
                            return {{Model}}Mapper.toDto(entity);
                        }

                        /**
                         *
                         * Delete a {{Model}}
                         *
                         */
                        @Transactional
                        public void delete({{KeyType}} {{key}}){
                            {{Model}}Entity entity=repository.findBy{{Key}}({{key}})
                                    .orElseThrow(()-> new ModelNotFoundException("{{Model}}", {{key}}));
                            repository.delete(entity);
                        }
                    }
                    """;

    /**
     * A Messager to emit messages during annotation processing
     */
    private Messager messager;

    /**
     *
     * @return the latest supported version of Java
     */
    @Override
    public SourceVersion getSupportedSourceVersion() {
        return SourceVersion.latestSupported();
    }

    /**
     * Initializes the processor with the processing environment
     *
     * @param processingEnv environment to access facilities the tool framework
     */
    @Override
    public synchronized void init(ProcessingEnvironment processingEnv) {
        messager = processingEnv.getMessager();
        super.init(processingEnv);
    }


    @Override
    public boolean process(Set<? extends TypeElement> annotations, RoundEnvironment roundEnv) {

        for (Element element : roundEnv.getElementsAnnotatedWith(GenerateService.class)) {

            // the annotation can only be used on a record
            if (element.getKind() != ElementKind.RECORD) {
                messager.printMessage(Diagnostic.Kind.ERROR, "@GenerateService ne peut être placé que sur un record", element);
                continue;
            }

            // the service uses the entity, the repository and the mapper : they must be generated too
            if (element.getAnnotation(GenerateEntity.class) == null
                    || element.getAnnotation(GenerateRepository.class) == null
                    || element.getAnnotation(GenerateMapper.class) == null) {
                messager.printMessage(Diagnostic.Kind.ERROR,
                        "@GenerateService nécessite aussi @GenerateEntity, @GenerateRepository et @GenerateMapper sur le record", element);
                continue;
            }

            TypeElement model = (TypeElement) element;

            // get the model class name
            String modelName=model.getSimpleName().toString();
            String serviceName=modelName+"Service";

            // the business key : the only field with @Unique (Role -> name)
            List<? extends RecordComponentElement> keys = model.getRecordComponents().stream()
                    .filter(field -> field.getAnnotation(Unique.class) != null)
                    .toList();

            if (keys.size() != 1) {
                messager.printMessage(Diagnostic.Kind.ERROR,
                        "@GenerateService : le record doit avoir exactement un champ @Unique (la clé métier), il en a "+keys.size(), element);
                continue;
            }

            RecordComponentElement key = keys.get(0);
            String keyType = key.asType().toString();
            String keyName = key.getSimpleName().toString();
            String KeyName = keyName.substring(0, 1).toUpperCase() + keyName.substring(1);

            //the class patern : we replace the markers

            String serviceClass=SERVICE_CLASS_PATTERN
                    .replace("{{Model}}", modelName)
                    .replace("{{KeyType}}", keyType)
                    .replace("{{Key}}", KeyName)
                    .replace("{{key}}", keyName);

            // we write the .java file : javac will compile it

            try{
                var file=processingEnv.getFiler().createSourceFile(SERVICE_PACKAGE+"."+serviceName,model);
                try(Writer writer=file.openWriter()){
                    writer.write(serviceClass);
                }
                messager.printMessage(Diagnostic.Kind.NOTE, "Service generation for %s (%s)".formatted(modelName, serviceName));
            } catch (IOException e) {
                messager.printMessage(Diagnostic.Kind.ERROR, "Impossible de générer "+serviceName, model);
            }
        }
        return true;
    }
}